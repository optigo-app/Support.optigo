export const getGreetingMeta = (hour = new Date().getHours()) => {
  if (hour >= 5 && hour < 12) {
    return {
      period: "morning",
      greeting: "Good Morning",
      Icon: MorningIcon,
      bg: "#FFF7ED",
      border: "#FFEDD5",
      accent: "#EA580C",
      glow: "rgba(255, 130, 45, 0.25)",
      tooltip: "Morning Time",
    };
  }
  if (hour >= 12 && hour < 17) {
    return {
      period: "afternoon",
      greeting: "Good Afternoon",
      Icon: AfternoonIcon,
      bg: "#FEFCE8",
      border: "#FEF08A",
      accent: "#CA8A04",
      glow: "rgba(252, 213, 63, 0.25)",
      tooltip: "Afternoon Time",
    };
  }
  if (hour >= 17 && hour < 21) {
    return {
      period: "evening",
      greeting: "Good Evening",
      Icon: EveningIcon,
      bg: "#FEF2F2",
      border: "#FEE2E2",
      accent: "#D97706",
      glow: "rgba(252, 194, 27, 0.25)",
      tooltip: "Evening Time",
    };
  }
  return {
    period: "night",
    greeting: "Good Night",
    Icon: NightIcon,
    bg: "#EEF2FF",
    border: "#E0E7FF",
    accent: "#4338CA",
    glow: "rgba(51, 103, 214, 0.25)",
    tooltip: "Night Time",
  };
};
